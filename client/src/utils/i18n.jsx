// ── Interpolation helper ─────────────────────────────────────────────────────
// Usage: interpolate('{nick} pinned a message', { nick: 'Alex' })
export function interpolate(str, vars) {
  if (!str) return '';
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ''));
}

